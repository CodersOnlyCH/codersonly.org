<template>
  <h1>Bylaws</h1>

  <h2 id="statuten-des-vereins">Statuten des Vereins</h2>

  <h3 id="1-name-und-sitz">1. Name und Sitz</h3>

  <p>
    Unter dem Namen “Coders Only” besteht ein Verein im Sinne von Art. 60 ff.
    ZGB mit Sitz in Zürich.
  </p>

  <h3 id="2-zweck">2. Zweck</h3>
  <p>
    Der Verein bezweckt, Theorie und Anwendung von
    Software-Development-Konzepten, -Methoden und verwandte Themen in der
    Schweiz zu fördern. Er dient als Informationsdrehscheibe, unterstützt den
    Erfahrungsaustausch unter ihren Mitgliedern und unterstützt die Kooperation
    von Firmen und akademischen Instituten. Wissenschaftliche Erkenntnisse sowie
    Erfahrungen aus der Praxis sollen den Mitgliedern leichter zugänglich
    gemacht und Erfahrungen bei der Anwendung neuer Methoden und Hilfsmittel
    weitergegeben werden.
  </p>

  <p>
    Der Verein organisiert Tagungen, Workshops, Besuche oder andere Aktivitäten.
    Diese richten sich nach dem Bedarf der Mitglieder.
  </p>

  <p>
    Der Verein hat keinen kommerziellen Zweck und ist politisch und
    konfessionell neutral.
  </p>

  <h3 id="3-migliedschaft">3. Migliedschaft</h3>

  <h4 id="31-mitgliedschaftsformen">3.1 Mitgliedschaftsformen</h4>
  <p>
    Mitglieder sind natürliche und juristische Person, die ein Interesse am
    Vereinszweck haben. Diese können in den folgenden Formen auftreten.
  </p>

  <h4 id="311-einzelmitglieder">3.1.1 Einzelmitglieder</h4>
  <p>
    Einzelmitglieder sind natürliche Personen In Ausbildung befindliche Personen
    werden auf Antrag und gegen Vorweisung einer Legitimation als
    Studentenmitglieder aufgenommen. Einzelmitglieder können per Beschluss der
    Mitgliederversammlung zu Ehrenmitgliedern ernannt werden.
  </p>

  <h4 id="312-kollektivmitglieder">3.1.2 Kollektivmitglieder</h4>
  <p>
    Kollektivmitglieder sind juristische Personen. Das Kollektivmitglied benennt
    eine Kontaktperson, an welche die an alle Mitglieder gerichtete
    Korrespondenz in einfacher Ausfertigung gesandt wird. Ein Kollektivmitglied
    hat das gleiche Stimmengewicht wie ein Einzelmitglied.
  </p>

  <h4 id="313-sponsormitglieder">3.1.3 Sponsormitglieder</h4>
  <p>
    Sponsormitglieder sind Kollektivmitglieder, welchen zusätzlich das nicht
    exklusive Recht eingerumt wird, das Attribut “Sponsormitglied” zu
    Werbezwecken einzusetzen.
  </p>

  <h3 id="32-rechte-und-pflichten">3.2 Rechte und Pflichten</h3>
  <p>
    Mitglieder haben das Stimm- und Wahlrecht an der Generalversammlung. Sie
    sind verpflichtet, die Ziele des Vereins zu unterstützen und aktiv am
    Vereinsleben teilzunehmen.
  </p>

  <h3 id="33-mitgliedschaftsantrag">3.3 Mitgliedschaftsantrag</h3>
  <p>
    Aufnahmegesuche sind an die auf der Homepage publizierte Vereinsadresse zu
    richten; über die Aufnahme entscheidet der Vorstand.
  </p>

  <h3 id="34-erlöschung-der-migliedschaft">3.4 Erlöschung der Migliedschaft</h3>
  <p>Die Mitgliedschaft erlischt:</p>
  <ol>
    <li>bei natürlichen Personen durch Austritt, Ausschluss oder Tod</li>
    <li>bei juristischen Personen durch Austritt, Ausschluss oder Auflösung</li>
  </ol>

  <h4 id="341-austritt">3.4.1 Austritt</h4>
  <p>
    Ein Austritt ist per Ende des laufenden Geschäftsjahres möglich. Das
    Austrittsschreiben muss schriftlich in Briefform oder per E-Mail bis zum 31.
    Dezember an die auf der Homepage publizierte Vereinsadresse gerichtet
    werden, wobei der laufende Jahresbeitrag vollständig geschuldet bleibt.
  </p>

  <h4 id="342-ausschluss">3.4.2 Ausschluss</h4>
  <p>
    Ein Mitglied kann jederzeit ohne Grundangabe aus dem Verein ausgeschlossen
    werden. Der Vorstand fällt den Ausschlussentscheid. Ausschlüsse, die auf
    Grundlage eines Verstosses gegen den Code of Conduct erfolgen, sollen
    transparent, fair und unter Wahrung der Verhältnismässigkeit geschehen.
    Betroffene Mitglieder haben das Recht, den Ausschlussentscheid an die
    Generalversammlung weiterzuziehen. Die Generalversammlung entscheidet mit
    einfachem Mehr der anwesenden Mitglieder über den Ausschluss. Mitglieder,
    die nach zweimaliger Mahnung ihren Jahresbeitrag nicht bezahlen, werden aus
    dem Verein ausgeschlossen.
  </p>

  <h3 id="4-organe">4. Organe</h3>
  <p>Die Organe des Vereins sind:</p>
  <ol>
    <li>die Generalversammlung</li>
    <li>der Vorstand</li>
  </ol>
  <p>Über die Beschlüsse der Organe ist Protokoll zu führen.</p>

  <h4 id="41-generalversammlung">4.1 Generalversammlung</h4>
  <p>
    Das oberste Organ des Vereins ist die Generalversammlung. Eine ordentliche
    Generalversammlung findet jährlich statt und wird vom Vorstand einberufen.
  </p>

  <p>
    Darüber hinaus können ausserordentliche Generalversammlungen durch den
    Vorstand, sowie auf schriftlichen Antrag von 10% der Mitglieder einberufen
    werden.
  </p>

  <p>
    Die Traktanden und Wahlvorschläge an der Generalversammlung werden durch den
    Vorstand festgelegt. Jedes Mitglied des Vereins hat das Recht, weitere
    Traktanden und Wahlvorschläge zu beantragen. Diese müssen bis spätestens 7
    Tage nach dem Versand der Einladung zur Generalversammlung schriftlich in
    Briefform oder per E-Mail an die auf der Homepage publizierte Vereinsadresse
    gerichtet werden.
  </p>

  <p>
    Die schriftliche Einladung zur Generalversammlung hat mit der
    Traktandenliste wenigstens 30 Tage im Voraus zu erfolgen. Die Einladung zur
    Generalversammlung kann wahlweise schriftlich per Post oder elektronisch per
    E-Mail erfolgen. Ist dies erfüllt, so ist die Generalversammlung
    beschlussfähig. An der Generalversammlung besitzt jedes Mitglied eine
    Stimme; die Beschlussfassung und Wahl erfolgt mit einfachem Mehr der
    anwesenden Mitglieder, bei Änderungen der Statuten mit Zweidrittelmehrheit
    der anwesenden Mitglieder. Über nicht traktandierte Geschäfte darf kein
    Beschluss gefasst werden.
  </p>

  <p>Die Generalversammlung hat die folgenden unentziehbaren Aufgaben:</p>
  <ol>
    <li>Wahl bzw. Abwahl des Vorstandes</li>
    <li>Wahl des Präsidenten des Vorstandes</li>
    <li>Festsetzung und Änderung der Statuten</li>
    <li>Abnahme der Jahresrechnung</li>
    <li>Entlastung des Vorstandes</li>
    <li>Beschluss über das Jahresbudget</li>
    <li>Festsetzung des Mitgliederbeiträge</li>
    <li>Behandlung der Ausschlussrekurse</li>
    <li>Zweckänderung und Auflösung des Vereins</li>
  </ol>

  <p>
    Anstelle eines Entscheides in der Generalversammlungen kann der Vorstand
    einen Briefentscheid oder elektronische Internetabstimmung der Mitglieder
    einholen. In diesem Fall müssen zwischen dem Versand der Stimmunterlagen und
    dem Termin für die Einsendung der Stimmzettel mindestens 30 Tage liegen.
  </p>

  <h3 id="42-vorstand">4.2 Vorstand</h3>
  <p>
    Der Vorstand besteht aus einem Präsidenten, einem Vizepräsidenten, einem
    Kassier und weiteren Mitgliedern. Ausser der Wahl des Präsidenten
    konstituiert der Vorstand sich selbst.
  </p>

  <p>
    Der Vorstand vertritt den Verein nach aussen und führt die laufenden
    Geschäfte, er wird rechtskräftig vertreten durch die Kollektivunterschrift
    des Präsidenten zusammen mit einem weiteren Mitglied des Vorstandes.
  </p>

  <p>
    Der Vorstand ist beschlussfähig, wenn mindestens die Hälfte der
    Vorstandsmitglieder anwesend sind. Er fasst seine Beschlüsse mit einfachem
    Mehr der anwesenden Mitglieder. Bei Stimmengleichheit kommt dem Präsidenten
    der Stichentscheid zu.
  </p>

  <p>
    Der Vorstand hat die Obhut über den Code of Conduct. Er ist zuständig für
    dessen Pflege, Auslegung und Anwendung sowie für die Unterstützung bei
    Konfliktfällen gemäss den darin beschriebenen Grundsätzen.
  </p>

  <p>
    Die Mitglieder des Vorstandes werden für eine Amtsdauer von einem Jahr
    gewählt.
  </p>

  <h3 id="5-regelwerke-und-ordnungen">5. Regelwerke und Ordnungen</h3>
  <p>
    Zur Erfüllung des Vereinszwecks kann der Verein ergänzende Regelwerke und
    Ordnungen erlassen. Dazu zählt insbesondere der Code of Conduct, welcher die
    Werte, das Verhalten und den Umgang innerhalb des Vereins konkretisiert.
  </p>

  <p>
    Der Vorstand ist zuständig für die Ausarbeitung, Pflege und Auslegung
    solcher Ordnungen. Änderungen dieser Ordnungen werden von der
    Generalversammlung mit einfachem Mehr der anwesenden Mitglieder bestätigt
    oder abgelehnt.
  </p>

  <p>
    Die Regelwerke sind für alle Mitglieder verbindlich, sobald sie von der
    Generalversammlung angenommen oder bestätigt wurden.
  </p>

  <h3 id="6-kommunikation">6. Kommunikation</h3>
  <p>
    Die Kommunikation des Vereins mit den Mitgliedern erfolgt postalisch
    und/oder elektronisch. Jedes Mitglied bezeichnet sowohl eine Post-Adresse
    wie auch eine E-Mail-Adresse, welche der Verein wahlweise zur Anschrift des
    Mitgliedes verwenden kann.
  </p>

  <h3 id="7-finanzielles">7. Finanzielles</h3>

  <h4 id="71-mittel">7.1 Mittel</h4>
  <p>
    Die Mittel des Vereins setzen sich aus Mitgliederbeiträgen und
    Sponsoringbeiträgen zusammen. Die Höhe der Einzel- und
    Kollektivmitgliederbeiträge wird jährlich von der Mitgliederversammlung
    festgelegt. Die Höhe der Studentenmitgliederbeiträge und der
    Sponsormitgliederbeiträge wird durch den Vorstand festgelegt.
  </p>

  <h4 id="72-geschäftsjahr">7.2 Geschäftsjahr</h4>
  <p>Das Geschäftsjahr entspricht dem Kalenderjahr.</p>

  <h4 id="73-revision">7.3 Revision</h4>
  <p>
    Ab einem Jahresumsatz von 10’000 CHF wählt die Generalversammlung jährlich
    einen oder mehrere Rechnungsrevisoren, welche die Buchführung kontrollieren.
    Die Revision prüft die Jahresrechnung und erstattet hierüber schriftlich
    Bericht zuhanden der Mitglieder. Bis zu einem Jahresumsatz von 10’000 CHF
    wird kein Rechnungsrevisor bestellt und eine vereinfachte Jahresrechnung
    erstellt.
  </p>

  <h4 id="74-haftung">7.4 Haftung</h4>
  <p>
    Für die Schulden des Vereins haftet ausschliesslich das Vereinsvermögen. Die
    persönliche Haftung und insbesondere eine Nachschusspflicht der Mitglieder
    ist ausgeschlossen.
  </p>

  <h3 id="8-statutenänderung">8. Statutenänderung</h3>
  <p>
    Der Vorstand oder 10% der Mitglieder können eine Änderung der Statuten
    beantragen. Der Wortlaut des Änderungsantrages ist der Traktandenliste der
    darüber beschliessenden Generalversammlung beizulegen.
  </p>

  <p>
    Die vorliegenden Statuten können abgeändert werden, wenn zwei Drittel der
    anwesenden Mitglieder dem Änderungsvorschlag zustimmen.
  </p>

  <h3 id="9-auflösung-des-vereins">9. Auflösung des Vereins</h3>
  <p>
    Über die Auflösung des Vereins sowie die Verwendung des Vereinsvermögens
    beschliesst die Mitgliederversammlung mit Zweidrittelmehrheit der anwesenden
    Mitglieder.
  </p>

  <p>
    Bei einer Auflösung des Vereins fällt das Vereinsvermögen an eine
    Institution, welche den gleichen oder einen ähnlichen Zweck verfolgt.
  </p>

  <h3 id="10-inkrafttreten">10. Inkrafttreten</h3>
  <p>
    Diese Statuten sind an der Generalversammlung vom 24. Juni 2025 angenommen
    worden und sind mit diesem Datum in Kraft getreten.
  </p>
